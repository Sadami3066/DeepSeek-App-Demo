val LocalOdColors = staticCompositionLocalOf { OdLightColors }

object OdTheme {
    val colors: OdColors
        @Composable get() = LocalOdColors.current

    val isDark: Boolean
        @Composable get() = OdTheme.colors === OdDarkColors
}


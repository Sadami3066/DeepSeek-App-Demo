@Composable
fun OpenDSTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    val colors = if (darkTheme) OdDarkColors else OdLightColors
    CompositionLocalProvider(LocalOdColors provides colors) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkScheme else LightScheme,
            typography = OpenDSTypography,
            content = content,
        )
    }
}
